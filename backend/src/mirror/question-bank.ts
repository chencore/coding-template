/**
 * 内置镜子问题库：LLM 不可用 / 无历史回答时的兜底，保证「镜子时刻永远可用」。
 * 风格约束（与 LLM prompt 一致）：温和、不评判、一句问句、≤40 字。
 */
export const QUESTION_BANK: readonly string[] = [
  "今天有没有一个瞬间，让你觉得「这才是我」？",
  "如果明天手机坏了，你最先想做什么？",
  "最近有什么事，你一直在想却还没说出口？",
  "这一周，你的身体在哪个时刻最放松？",
  "你今天为什么事情花了最多的注意力？它值得吗？",
  "有没有一个人，你最近想联系却一直没联系？",
  "如果给昨天的自己发条消息，你会说什么？",
  "今天刷手机时，哪条内容让你停下来了？为什么？",
  "你现在的生活里，哪件事是「应该有」而非「想要」？",
  "今天有什么小事，比你预期的要好？",
  "你上一次完全不看屏幕的一个小时，在做什么？",
  "最近一次你拒绝别人，是什么时候？感觉如何？",
  "今天的你，会怎样形容现在的心情天气？",
  "此刻你最想被问的一个问题是什么？",
];

/** 按日期轮换选取：同一天恒定，逐日递进 */
export function pickBankQuestion(entryDate: string): string {
  let hash = 0;
  for (const ch of entryDate) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return QUESTION_BANK[hash % QUESTION_BANK.length];
}
